load_dotenv()

# Reuse uvicorn's logger so messages always show up in the terminal running the server.
logger = logging.getLogger("uvicorn.error")

# The URL can be overridden (e.g. to point the tests at a fake provider).
RODIUMAI_URL = os.getenv("RODIUMAI_URL", "https://api.rodiumai.io/v1/chat/completions")
RODIUMAI_API_KEY = os.environ["RODIUMAI_API_KEY"]
MODEL = os.getenv("RODIUMAI_MODEL", "anthropic/claude-sonnet-4-5-20250929")  # default model
# Models the user may choose from: defined on the server only (.env), never trusted from the client.
ALLOWED_MODELS = [m.strip() for m in os.getenv("ALLOWED_MODELS", MODEL).split(",") if m.strip()]
if MODEL not in ALLOWED_MODELS:
    ALLOWED_MODELS.insert(0, MODEL)
PREVIEW_LENGTH = 60

# ---------------------------------------------------------------------------
# Roles
# ---------------------------------------------------------------------------
# Roles the LLM understands: sent to it as they are.
LLM_ROLES = {"user", "assistant"}

NOTIFICATION_ROLE = "system-notification"
# Custom roles (the column `messages.role` is a String(20): keep names short).
NOTE_ROLE = "note"        # personal note written by the student
QUIZ_ROLE = "quiz"        # revision question generated by the tutor every N answers
SUMMARY_ROLE = "summary"  # periodic summary of the conversation

# How each stored role reaches the LLM (every role is handled explicitly in build_llm_history):
# - FILTERED: interface-only messages, never sent to the LLM.
#     note: private to the student. summary: derived from a history the LLM already receives in full.
#     system-notification: a message from the system to the student.
# - TRANSFORMED: sent under a standard role.
#     quiz -> "assistant": it is the tutor's own question, and the LLM needs it to understand the student's answer.
HIDDEN_ROLES = {NOTIFICATION_ROLE, NOTE_ROLE, SUMMARY_ROLE}
TRANSFORMED_ROLES = {QUIZ_ROLE: "assistant"}

# ---------------------------------------------------------------------------
# Triggers (counted on the dialogue only: user + assistant messages)
# ---------------------------------------------------------------------------
# a notification each time the dialogue reaches a multiple of this many messages
NOTIFICATION_EVERY = 10
NOTIFICATION_TEXT = "Notification système : Une dizaine de messages écrits."
# a quiz question / a summary every N answers of the tutor
QUIZ_EVERY_ANSWERS = 3
SUMMARY_EVERY_ANSWERS = 4

# The system prompt lives in its own file (prompts/system.md). SYSTEM_PROMPT_FILE lets the test sheet
# compare it with the old two-line prompt (prompts/old.md).
PROMPT_FILE = os.getenv("SYSTEM_PROMPT_FILE", "prompts/system.md")
SYSTEM_PROMPT = (Path(__file__).parent / PROMPT_FILE).read_text(encoding="utf-8")

QUIZ_PROMPT = (
    "Tu es Study Buddy, un tuteur bienveillant. À partir de la conversation ci-dessous, "
    "pose UNE seule question de révision sur ce qui vient d'être vu. "
    "Ne donne pas la réponse. Écris uniquement la question, en une ou deux phrases, en français."
)

SUMMARY_PROMPT = (
    "Tu es Study Buddy, un tuteur bienveillant. Résume la conversation ci-dessous en 3 à 5 points "
    "courts (liste à puces) : les notions abordées et les conclusions importantes. En français."
)

app = FastAPI(title="Study Buddy Chatbot")


class ConversationResponse(BaseModel):
    conversation_id: int


class ConversationSummary(BaseModel):
    id: int
    created_at: datetime
    preview: str | None  # first user message, truncated; None while the conversation is empty


class ChatRequest(BaseModel):
    conversation_id: int
    message: str
    model: str | None = None  # must be one of ALLOWED_MODELS; the default model is used when omitted


class ModelsResponse(BaseModel):
    models: list[str]
    default: str


class ChatResponse(BaseModel):
    reply: str
    # each one is set when this turn also stored a message with that role
    notification: str | None = None
    summary: str | None = None
    quiz: str | None = None


class NoteRequest(BaseModel):
    # Surrounding spaces are removed, then the note must still contain at least one character.
    content: Annotated[str, StringConstraints(strip_whitespace=True, min_length=1, max_length=2000)]


class MessageResponse(BaseModel):
    seq: int
    role: str
    content: str
    created_at: datetime


class LLMError(Exception):
    """The LLM call failed (network, HTTP error or unexpected response). Details are already logged."""


def call_llm(messages: list[dict], max_tokens: int, model: str = MODEL) -> str:
    # One non-streaming call to the LLM; returns the text of the answer.
    try:
        response = httpx.post(
            RODIUMAI_URL,
            headers={"Authorization": f"Bearer {RODIUMAI_API_KEY}"},
            json={
                "model": model,
                "messages": messages,
                "max_tokens": max_tokens,
                "stream": False,
            },
            timeout=30,
        )
        response.raise_for_status()
        return response.json()["choices"][0]["message"]["content"]
    except httpx.HTTPStatusError as exc:
        # The provider answered with an error code: log it so the real cause is visible.
        logger.error(
            "LLM API returned %s (model=%s): %s",
            exc.response.status_code, model, exc.response.text[:500],
        )
        raise LLMError from exc
    except httpx.HTTPError as exc:
        # No answer at all (timeout, network, DNS...).
        logger.error("LLM API unreachable (model=%s): %r", model, exc)
        raise LLMError from exc
    except (KeyError, IndexError, ValueError) as exc:
        logger.error("LLM API returned an unexpected response (model=%s): %r", model, exc)
        raise LLMError from exc


def generate_extra(instruction: str, request: str, turn: list[dict], max_tokens: int, model: str = MODEL) -> str | None:
    # Best effort: a quiz or a summary is a bonus. If the call fails, the turn still succeeds without it.
    messages = [{"role": "system", "content": instruction},
                *turn, {"role": "user", "content": request}]
    try:
        return call_llm(messages, max_tokens, model).strip() or None
    except LLMError:
        return None


def stream_llm(messages: list[dict], max_tokens: int, model: str) -> Iterator[str]:
    # One streaming call: yields the text pieces (choices[0].delta.content) as they arrive.
    # The provider sends lines "data: {...}" and ends with "data: [DONE]".
    # A stream that stops before the end (network cut, provider error) raises LLMError.
    finished = False
    try:
        with httpx.stream(
            "POST",
            RODIUMAI_URL,
            headers={"Authorization": f"Bearer {RODIUMAI_API_KEY}"},
            json={"model": model, "messages": messages, "max_tokens": max_tokens, "stream": True},
            timeout=60,
        ) as response:
            if response.status_code >= 400:
                response.read()
                logger.error("LLM API returned %s (model=%s): %s", response.status_code, model, response.text[:500])
                raise LLMError
            for line in response.iter_lines():
                if not line.startswith("data:"):
                    continue
                payload = line[len("data:"):].strip()
                if payload == "[DONE]":
                    finished = True
                    break
                try:
                    chunk = json.loads(payload)
                except ValueError:
                    continue
                if "error" in chunk:
                    logger.error("LLM API error in the stream (model=%s): %s", model, str(chunk["error"])[:500])
                    raise LLMError
                choices = chunk.get("choices") or []
                if not choices:
                    continue
                delta = (choices[0].get("delta") or {}).get("content")
                if delta:
                    yield delta
                if choices[0].get("finish_reason"):
                    finished = True
    except httpx.HTTPError as exc:
        logger.error("LLM stream interrupted (model=%s): %r", model, exc)
        raise LLMError from exc
    if not finished:
        logger.error("LLM stream ended before [DONE] (model=%s).", model)
        raise LLMError


def resolve_model(requested: str | None) -> str:
    # Never trust the client: only models listed on the server are accepted.
    if requested is None:
        return MODEL
    if requested not in ALLOWED_MODELS:
        raise HTTPException(status_code=400, detail=f"Model not allowed: {requested!r}.")
    return requested


def load_messages(db: Session, conversation_id: int) -> list[Message]:
    # A conversation's messages in order; 404 if the conversation doesn't exist.
    if db.get(Conversation, conversation_id) is None:
        raise HTTPException(status_code=404, detail="Conversation not found.")
    return db.scalars(
        select(Message)
        .where(Message.conversation_id == conversation_id)
        .order_by(Message.seq)
    ).all()


def build_llm_history(rows: list[Message]) -> list[dict]:
    # The DB history is not what the LLM sees. Every stored role is handled explicitly, just before building the request:
    # - user / assistant: sent as they are.
    # - TRANSFORMED_ROLES (quiz): sent under a standard role.
    # - HIDDEN_ROLES (note, summary, system-notification): filtered out.
    # - anything else: skipped with a warning, so an unknown role never reaches the LLM by accident.
    history: list[dict] = []
    for m in rows:
        if m.role in LLM_ROLES:
            role = m.role
        elif m.role in TRANSFORMED_ROLES:
            role = TRANSFORMED_ROLES[m.role]
        elif m.role in HIDDEN_ROLES:
            continue
        else:
            logger.warning("Unknown message role %r (seq=%s): skipped.", m.role, m.seq)
            continue
        # A transformed message can follow a message of the same role (the answer, then the quiz):
        # merge them, because providers do not all accept two consecutive messages with the same role.
        if history and history[-1]["role"] == role:
            history[-1]["content"] += "\n\n" + m.content
        else:
            history.append({"role": role, "content": m.content})
    return history


@app.post("/conversations", status_code=201)
def create_conversation(db: Session = Depends(get_db)) -> ConversationResponse:
    conversation = Conversation()
    db.add(conversation)
    db.commit()
    return ConversationResponse(conversation_id=conversation.id)


@app.get("/conversations")
def list_conversations(db: Session = Depends(get_db)) -> list[ConversationSummary]:
    # Newest first, each joined to its first message (seq 1, always the user's) for the preview.
    rows = db.execute(
        select(Conversation, Message.content)
        .outerjoin(Message, and_(Message.conversation_id == Conversation.id, Message.seq == 1))
        .order_by(Conversation.id.desc())
    ).all()
    return [
        ConversationSummary(
            id=conversation.id,
            created_at=conversation.created_at,
            preview=content[:PREVIEW_LENGTH] if content else None,
        )
        for conversation, content in rows
    ]


@app.get("/conversations/{conversation_id}/messages")
def list_messages(conversation_id: int, db: Session = Depends(get_db)) -> list[MessageResponse]:
    # Returns every stored row (notes, quizzes, summaries, notifications included): the interface styles each role.
    return [
        MessageResponse(seq=m.seq, role=m.role,
                        content=m.content, created_at=m.created_at)
        for m in load_messages(db, conversation_id)
    ]


@app.post("/conversations/{conversation_id}/notes", status_code=201)
def add_note(conversation_id: int, req: NoteRequest, db: Session = Depends(get_db)) -> MessageResponse:
    # Store a personal note as a message with the custom role. No LLM call involved.
    rows = load_messages(db, conversation_id)
    if not rows:
        # The conversation preview reads the message with seq 1, which must be the user's first message.
        raise HTTPException(
            status_code=409, detail="Send a first message before adding a note.")

    note = Message(conversation_id=conversation_id,
                   seq=rows[-1].seq + 1, role=NOTE_ROLE, content=req.content)
    db.add(note)
    try:
        db.commit()
    except IntegrityError:
        # Another request took this seq number in the meantime.
        db.rollback()
        raise HTTPException(
            status_code=409, detail="The conversation was updated concurrently, please retry."
        )
    db.refresh(note)
    return MessageResponse(seq=note.seq, role=note.role,
                           content=note.content, created_at=note.created_at)


@app.get("/models")
def list_models() -> ModelsResponse:
    # The list is defined on the server (ALLOWED_MODELS in .env); the interface only displays it.
    return ModelsResponse(models=ALLOWED_MODELS, default=MODEL)


def sse(event: dict) -> str:
    # One server-sent-event line, read by the frontend with fetch + getReader().
    return f"data: {json.dumps(event, ensure_ascii=False)}\n\n"


def store_turn(
    db: Session,
    conversation_id: int,
    next_seq: int,
    dialogue_count: int,
    history: list[dict],
    user_message: dict,
    reply: str,
    model: str,
) -> ChatResponse:
    # Shared by /chat and /chat/stream: build the extra messages (notification, summary, quiz) and record
    # the whole turn in ONE transaction, once the reply is complete.
    # dialogue_count = user + assistant stored rows, plus this turn: the extra roles
    # never shift the totals that trigger notifications, summaries and quizzes.
    answers = dialogue_count // 2

    # Extra messages stored after the turn, in this order (the quiz comes last: the student answers it next).
    extras: list[tuple[str, str]] = []
    notification = summary = quiz = None
    turn = [*history, user_message, {"role": "assistant", "content": reply}]

    if dialogue_count % NOTIFICATION_EVERY == 0:
        notification = NOTIFICATION_TEXT
        extras.append((NOTIFICATION_ROLE, notification))

    if answers % SUMMARY_EVERY_ANSWERS == 0:
        summary = generate_extra(
            SUMMARY_PROMPT, "Résume maintenant la conversation.", turn, max_tokens=400, model=model)
        if summary:
            extras.append((SUMMARY_ROLE, summary))

    if answers % QUIZ_EVERY_ANSWERS == 0:
        quiz = generate_extra(
            QUIZ_PROMPT, "Pose maintenant ta question de révision.", turn, max_tokens=200, model=model)
        if quiz:
            extras.append((QUIZ_ROLE, quiz))

    # Only record the turn once the calls succeeded, so a failure doesn't leave a dangling user message.
    db.add_all([
        Message(conversation_id=conversation_id,
                seq=next_seq, role="user", content=user_message["content"]),
        Message(conversation_id=conversation_id,
                seq=next_seq + 1, role="assistant", content=reply),
    ])
    for offset, (role, content) in enumerate(extras, start=2):
        db.add(Message(conversation_id=conversation_id,
                       seq=next_seq + offset, role=role, content=content))

    try:
        db.commit()
    except IntegrityError:
        # Another request already wrote these seq numbers in this conversation while we waited for the LLM.
        db.rollback()
        raise HTTPException(
            status_code=409, detail="The conversation was updated concurrently, please retry."
        )
    return ChatResponse(reply=reply, notification=notification, summary=summary, quiz=quiz)


@app.post("/chat")
def chat(req: ChatRequest, db: Session = Depends(get_db)) -> ChatResponse:
    # Non-streaming version, kept for simple clients.
    model = resolve_model(req.model)
    # Load this conversation from the database, in message order.
    rows = load_messages(db, req.conversation_id)
    history = build_llm_history(rows)
    # seq follows every stored row (notes, quizzes, summaries, notifications included) so it stays unique.
    next_seq = rows[-1].seq + 1 if rows else 1
    dialogue_count = sum(1 for m in rows if m.role in LLM_ROLES) + 2
    user_message = {"role": "user", "content": req.message}

    # The LLM is stateless: resend the system prompt + the whole conversation each turn.
    messages = [{"role": "system", "content": SYSTEM_PROMPT},
                *history, user_message]

    try:
        reply = call_llm(messages, max_tokens=512, model=model)
    except LLMError as exc:
        raise HTTPException(
            status_code=502, detail="The LLM API call failed.") from exc

    return store_turn(db, req.conversation_id, next_seq, dialogue_count, history, user_message, reply, model)


@app.post("/chat/stream")
def chat_stream(req: ChatRequest) -> StreamingResponse:
    # Same turn as /chat, but the reply is sent piece by piece as it is generated.
    # Events (one JSON object per "data:" line):
    #   {"delta": "..."}                                    a piece of the reply
    #   {"done": true, "reply", "notification", "summary", "quiz"}   the turn is stored
    #   {"error": "..."}                                    nothing was stored
    model = resolve_model(req.model)

    # Read what is needed to build the prompt, then close this session: the stream can last a while,
    # and the write below opens its own session. A missing conversation is still a normal 404.
    with SessionLocal() as db:
        rows = load_messages(db, req.conversation_id)
        history = build_llm_history(rows)
        next_seq = rows[-1].seq + 1 if rows else 1
        dialogue_count = sum(1 for m in rows if m.role in LLM_ROLES) + 2
    user_message = {"role": "user", "content": req.message}
    messages = [{"role": "system", "content": SYSTEM_PROMPT},
                *history, user_message]

    def event_stream() -> Iterator[str]:
        pieces: list[str] = []
        try:
            for delta in stream_llm(messages, 512, model):
                pieces.append(delta)
                yield sse({"delta": delta})
            reply = "".join(pieces)
            if not reply.strip():
                raise LLMError
            # The stream is complete: only now is anything written (one transaction). If the stream broke
            # before this point, or the client left (Stop), the database has not been touched.
            with SessionLocal() as db:
                result = store_turn(
                    db, req.conversation_id, next_seq, dialogue_count, history, user_message, reply, model)
        except LLMError:
            yield sse({"error": "The LLM API call failed."})
            return
        except HTTPException as exc:
            yield sse({"error": exc.detail})
            return
        except Exception:
            logger.exception("Unexpected error while streaming the reply.")
            yield sse({"error": "Unexpected server error."})
            return
        yield sse({
            "done": True,
            "reply": result.reply,
            "notification": result.notification,
            "summary": result.summary,
            "quiz": result.quiz,
        })

    return StreamingResponse(
        event_stream(),
        media_type="text/event-stream",
        headers={"Cache-Control": "no-cache", "X-Accel-Buffering": "no"},
    )